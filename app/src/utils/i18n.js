const STORAGE_KEY = "xuji_display_language";

export function getStoredLanguage() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && TRANSLATIONS[saved]) return saved;
    if (typeof navigator !== "undefined" && navigator.language) {
      const navLang = navigator.language;
      if (TRANSLATIONS[navLang]) return navLang;
      const prefix = navLang.split("-")[0];
      const match = SUPPORTED_LANGUAGES.find((item) => item.code.startsWith(prefix));
      if (match) return match.code;
    }
  } catch (e) {
    // ignore
  }
  return "zh-CN";
}

export function setStoredLanguage(code) {
  try {
    if (TRANSLATIONS[code]) {
      localStorage.setItem(STORAGE_KEY, code);
      return true;
    }
  } catch (e) {
    // ignore
  }
  return false;
}

export function t(key, lang = null, params = {}) {
  const activeLang = lang || getStoredLanguage();
  const dict = TRANSLATIONS[activeLang] || TRANSLATIONS["zh-CN"] || {};
  let text = dict[key] || TRANSLATIONS["zh-CN"]?.[key] || key;
  if (params && typeof params === "object") {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(new RegExp(`\\{\\s*${k}\\s*\\}`, "g"), v);
    });
  }
  return text;
}
